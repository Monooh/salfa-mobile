export type Strings = typeof strings.en;
export const t = (locale: Locale): Strings => strings[locale] as unknown as Strings;

/** Prices per market and page count, VAT inclusive, as the web shows them. */
export const PRICES: Record<Market, Record<20 | 40, string>> = {
  KW: { 20: "18.000", 40: "28.000" },
  SA: { 20: "159", 40: "249" },
};
export function formatPrice(market: Market, pages: 20 | 40, locale: Locale): string {
  const s = t(locale);
  return `${PRICES[market][pages]} ${market === "KW" ? s.kd : s.sar}`;
}
